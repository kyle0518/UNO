#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
export PATH="$HOME/.cargo/bin:$PATH"

export TS_RS_EXPORT_DIR="$ROOT/apps/web/src/generated"
mkdir -p "$TS_RS_EXPORT_DIR"
rm -f "$TS_RS_EXPORT_DIR"/*.ts

echo "==> 產生 TypeScript 型別到 $TS_RS_EXPORT_DIR"
cargo test -p uno-core -p uno-protocol export_bindings

{
  echo "// This file was generated by scripts/gen-types.sh. Do not edit this file manually."
  for f in "$TS_RS_EXPORT_DIR"/*.ts; do
    base="$(basename "$f" .ts)"
    [ "$base" = "index" ] && continue
    echo "export type * from './${base}';"
  done | LC_ALL=C sort
} > "$TS_RS_EXPORT_DIR/index.ts"
